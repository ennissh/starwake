#!/usr/bin/env bash
###############################################################################
# install.sh - install (or reconfigure) Starwake on this Docker host (dwarf)
#
# Works on its own: no checkout needed. On dwarf:
#   curl -fsSLO https://raw.githubusercontent.com/ennissh/starwake/main/install.sh
#   sudo bash install.sh
#
#   sudo ./install.sh                     interactive: asks every setting, probes Ollama, starts it
#   sudo ./install.sh --non-interactive   answers from STARWAKE_*/OLLAMA_*/... environment
#                                         variables, else the existing .env, else defaults
# Options:
#   --dir DIR             install directory (default /opt/docker/starwake)
#   --tag TAG             image tag (default: latest, or the saved one)
#   --settings MODE       when .env exists: saved (use it, no questions), review (ask each,
#                         saved values as defaults) or fresh (ask each, built-in defaults)
#   --no-start            write compose.yaml and .env; pull the image (for the Ollama probe) but
#                         start nothing (add --no-pull to skip the pull too)
#   --no-pull             use an image already on this host (e.g. from ./build.sh --local)
#   -h, --help            this help
#
# What it asks: install dir, port, hostname, image tag, data dir, translator mode, Ollama URL
# (probed from inside a container: the real path through DOCKER-USER), model (from the host's
# list), timeouts, content rating, log level, and whether to install a daily backup.
# It writes DIR/compose.yaml, DIR/.env (mode 600), DIR/backup.sh, DIR/restore.sh and chowns the data dir to
# uid 1000. Re-running is safe: saves are never touched, only settings you change.
#
# It never edits the firewall (docker-lan-only.sh), Pi-hole or other stacks: it checks and
# tells you what to change.
###############################################################################
set -euo pipefail

# ---------------------------------------------------------------------------- embedded files
# Copies of deploy/compose.yaml, scripts/backup.sh and scripts/restore.sh, so this one file is all dwarf needs.
# Generated by scripts/sync-installer.sh; ./test.sh fails if they drift from the originals.
embedded_compose() {
    cat <<'STARWAKE_EMBED_COMPOSE'
# Starwake on dwarf. install.sh copies this file and writes .env next to it; don't edit .env by hand
# unless you know the setting (re-run install.sh --settings review instead).
services:
  starwake:
    image: ${STARWAKE_IMAGE:-ghcr.io/ennissh/starwake}:${STARWAKE_TAG:-latest}
    container_name: ${STARWAKE_CONTAINER:-starwake}
    restart: unless-stopped
    env_file: .env
    ports:
      - '${PORT:-8090}:8080'
    volumes:
      - ${STARWAKE_DATA:-/opt/docker/starwake/data}:/data
    security_opt:
      - no-new-privileges:true
    read_only: true
    tmpfs:
      - /tmp
    healthcheck:
      test: ['CMD', 'node', 'apps/server/dist/healthcheck.js']
      interval: 30s
      timeout: 5s
      start_period: 10s
      retries: 3
    logging:
      driver: json-file
      options: { max-size: '10m', max-file: '3' }
STARWAKE_EMBED_COMPOSE
}
embedded_backup() {
    cat <<'STARWAKE_EMBED_BACKUP'
#!/usr/bin/env bash
###############################################################################
# backup.sh - dated tarball of the Starwake data directory, keeping the newest N
#
#   backup.sh [DATA_DIR] [BACKUP_DIR] [KEEP]
#   defaults:  /opt/docker/starwake/data  /opt/docker/starwake/backups  14
#
# Safe while the game runs: saves are written atomically (temp file + rename).
# Restore: stop the container, extract over an empty data dir, chown 1000:1000, start:
#   cd /opt/docker/starwake && sudo docker compose down
#   sudo mv data data.old && sudo mkdir data
#   sudo tar -xzf backups/starwake-data-<date>.tar.gz -C data && sudo chown -R 1000:1000 data
#   sudo docker compose up -d
###############################################################################
set -euo pipefail
DATA="${1:-/opt/docker/starwake/data}"
DEST="${2:-/opt/docker/starwake/backups}"
KEEP="${3:-14}"
[[ -d "$DATA" ]] || { echo "backup: data dir $DATA not found" >&2; exit 1; }
[[ "$KEEP" =~ ^[0-9]+$ && "$KEEP" -ge 1 ]] || { echo "backup: KEEP must be a positive number" >&2; exit 2; }
mkdir -p "$DEST"
stamp="$(date +%Y%m%d-%H%M%S)"
out="$DEST/starwake-data-$stamp.tar.gz"
tar -czf "$out.tmp" -C "$DATA" .
mv "$out.tmp" "$out"
echo "backup: wrote $out ($(du -h "$out" | cut -f1))"
# Keep the newest KEEP backups.
mapfile -t old < <(ls -1t "$DEST"/starwake-data-*.tar.gz 2>/dev/null | tail -n +"$((KEEP + 1))")
for f in "${old[@]}"; do rm -f -- "$f" && echo "backup: removed old $f"; done
STARWAKE_EMBED_BACKUP
}
embedded_restore() {
    cat <<'STARWAKE_EMBED_RESTORE'
#!/usr/bin/env bash
###############################################################################
# restore.sh - put a backup.sh tarball back as the Starwake data directory
#
#   restore.sh ARCHIVE [DATA_DIR]          (default /opt/docker/starwake/data)
#
# Stop the container first (sudo docker compose down). The current data directory is
# never deleted: it is moved aside to DATA_DIR.before-restore-<date>. The archive is
# checked before anything moves; files end up owned by uid 1000 (the container user).
###############################################################################
set -euo pipefail
ARCHIVE="${1:-}"
DATA="${2:-/opt/docker/starwake/data}"
[[ -n "$ARCHIVE" && -f "$ARCHIVE" ]] || { echo "restore: usage: restore.sh ARCHIVE [DATA_DIR]" >&2; exit 2; }
tar -tzf "$ARCHIVE" >/dev/null || { echo "restore: $ARCHIVE is not a readable tar.gz" >&2; exit 1; }
if command -v docker >/dev/null 2>&1 && docker ps --format '{{.Names}}' 2>/dev/null | grep -qx starwake; then
    echo "restore: the starwake container is running; stop it first (docker compose down)" >&2
    exit 1
fi
if [[ -e "$DATA" ]]; then
    aside="$DATA.before-restore-$(date +%Y%m%d-%H%M%S)"
    mv -- "$DATA" "$aside"
    echo "restore: kept the old data at $aside"
fi
mkdir -p "$DATA"
tar -xzf "$ARCHIVE" -C "$DATA"
if [[ "$(id -u)" == 0 ]]; then chown -R 1000:1000 "$DATA"; fi
echo "restore: $ARCHIVE → $DATA ($(find "$DATA" -type f | wc -l) files)"
STARWAKE_EMBED_RESTORE
}

