install_file() {  # install_file SRC DEST MODE : copies, keeping a .bak of a changed original
    local src="$1" dest="$2" mode="$3"
    if [[ -f "$dest" ]] && ! cmp -s "$src" "$dest"; then $SUDO cp -p "$dest" "$dest.bak"; fi
    $SUDO install -m "$mode" "$src" "$dest"
}
