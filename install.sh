INTERACTIVE=1 START=1 PULL=1 SETTINGS="" DIR_ARG="" TAG_ARG=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --non-interactive) INTERACTIVE=0 ;;
        --dir) [[ $# -ge 2 ]] || die "--dir needs a path"; DIR_ARG="$2"; shift ;;
