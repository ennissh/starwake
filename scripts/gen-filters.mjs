#!/usr/bin/env node
// Build content/filters.json from scripts/cleanroom-terms.txt and scripts/rating-terms.txt.
// Terms are stored as SHA-256 hashes of their lower-case form, so the shipped content and the
// clean-room grep never see the words. `--check` fails if the file is out of date (test.sh).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const h = (t) =>
  createHash('sha256').update(t.trim().toLowerCase().replace(/\s+/g, ' ')).digest('hex').slice(0, 24);
const lines = (f) =>
  readFileSync(f, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));

const out = {
  note: 'Generated by scripts/gen-filters.mjs; do not edit. SHA-256 (24 hex) of lower-case terms.',
  cleanroom: [],
  never: [],
  strong: [],
  crude: [],
};
for (const t of lines('scripts/cleanroom-terms.txt')) out.cleanroom.push(h(t));
let section = null;
for (const l of lines('scripts/rating-terms.txt')) {
  const m = /^\[(\w+)\]$/.exec(l);
  if (m) section = m[1];
  else if (section && out[section]) out[section].push(h(l));
}
for (const k of ['cleanroom', 'never', 'strong', 'crude']) out[k] = [...new Set(out[k])].sort();
const json = JSON.stringify(out, null, 2) + '\n';
const path = 'content/filters.json';
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(path, 'utf8');
  } catch {
    /* no file yet */
  }
  if (cur !== json) {
    console.error('content/filters.json is out of date: run node scripts/gen-filters.mjs');
    process.exit(1);
  }
  console.log('filters: ok');
} else {
  writeFileSync(path, json);
  console.log(`wrote ${path}`);
}
